// Static web version test: serves dist/ as plain files (no game server) and plays through the core loop.
import { createRequire } from 'node:module';
import http from 'node:http'; import fs from 'node:fs'; import path from 'node:path';
import assert from 'node:assert/strict';
const { chromium } = createRequire(import.meta.url)('playwright');
const DIST = path.resolve('dist'), OUT = process.env.SHOTS || './shots';
const MIME = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.json': 'application/json' };
const srv = http.createServer((req, res) => { let f = path.join(DIST, decodeURIComponent(req.url.split('?')[0])); if (f.endsWith('/')) f += 'index.html'; fs.readFile(f, (e, d) => { if (e) { res.writeHead(404); return res.end(); } res.writeHead(200, { 'Content-Type': MIME[path.extname(f)] || 'application/octet-stream' }); res.end(d); }); }).listen(3150);
const proxy = process.env.HTTPS_PROXY ? { server: process.env.HTTPS_PROXY } : undefined;
const browser = await chromium.launch({ proxy: proxy ? { ...proxy, bypass: 'localhost,127.0.0.1' } : undefined });
const ctx = await browser.newContext({ viewport: { width: 1000, height: 640 }, ignoreHTTPSErrors: true });
const page = await ctx.newPage();
const errors = [];
page.on('pageerror', e => errors.push('PAGEERROR ' + e.message)); page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
await page.addInitScript(() => { localStorage.setItem('st_seen_help', '1'); localStorage.setItem('st_cam', 'tps'); });
const sleep = ms => new Promise(r => setTimeout(r, ms));
const E = (fn, a) => page.evaluate(fn, a);
const waitFor = async (fn, ms = 20000) => { const t0 = Date.now(); while (Date.now() - t0 < ms) { if (await E(fn)) return; await sleep(200); } throw new Error('timeout ' + fn); };
await page.goto('http://localhost:3150/?low'); await sleep(2500);
await page.fill('#m-name', 'Solo'); await page.click('#m-create');
await waitFor(() => !document.getElementById('lobby').classList.contains('hidden'));
await page.click('#l-start');
await waitFor(() => window.__G.meta && window.__G.meta.phase === 'naming');
await page.fill('#n-input', 'Static Mart'); await sleep(300); await page.click('#n-vote');
await waitFor(() => window.__G.meta.phase === 'prep');
const comp = await E(() => window.__G.world.furniture.find(f => f.type === 'computer'));
await E(([x, z]) => { const m = window.__dbg.me; m.x = x; m.z = z; m.rot = -Math.PI / 2; }, [comp.x + 1.5, comp.z + 1]);
await waitFor(() => window.__dbg.lastInter?.action?.a === '_computer');
await page.keyboard.press('e'); await sleep(500);
await page.click('[data-goto="furniture"]'); await sleep(300);
await page.click('[data-act="buyf"][data-type="shelf"]');
await waitFor(() => window.__G.meta.orders.length === 1);
await page.keyboard.press('Escape');
await E(() => window.__dbg.net.act('speed', { v: 3 }));
await waitFor(() => window.__G.world.boxes.some(b => b.ftype === 'shelf'), 40000);
await page.click('#h-open');
await waitFor(() => window.__G.snap && window.__G.snap.phase === 'open');
await sleep(4000);
await page.screenshot({ path: `${OUT}/80-static-version.png` });
const saved = await E(() => Object.keys(JSON.parse(localStorage.getItem('st_local_saves') || '{}')).length);
console.log('static build: store opened, customers', await E(() => window.__G.snap.C.length), '| saves', saved);
console.log('errors:', errors.length ? errors.join('\n') : 'none');
await browser.close(); srv.close(); process.exit(errors.length ? 1 : 0);
